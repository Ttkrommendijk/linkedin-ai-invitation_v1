create or replace function public.record_project_item_event()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  event_name text;
begin
  if tg_op = 'INSERT' then
    event_name := 'created';
  elsif old.kind = 'idea' and new.kind = 'project' then
    event_name := 'promoted';
  elsif old.kind = 'project' and new.kind = 'idea' then
    event_name := 'demoted';
  elsif old.project_status is distinct from new.project_status then
    event_name := 'status_changed';
  else
    event_name := 'updated';
  end if;

  insert into public.project_events(owner_user_id, project_item_id, event_type, payload)
  values (
    new.owner_user_id,
    new.id,
    event_name,
    jsonb_build_object(
      'old_kind', case when tg_op = 'UPDATE' then old.kind else null end,
      'new_kind', new.kind,
      'old_status', case when tg_op = 'UPDATE' then old.project_status else null end,
      'new_status', new.project_status
    )
  );
  return new;
end;
$$;

create trigger trg_project_items_record_event
after insert or update on public.project_items
for each row execute function public.record_project_item_event();

create or replace function public.handle_project_demotion()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  if old.kind = 'project' and new.kind = 'idea' then
    update public.project_actions
    set status = 'cancelled'
    where project_id = new.id
      and owner_user_id = new.owner_user_id
      and status = 'open';
  end if;
  return new;
end;
$$;

create trigger trg_project_items_handle_demotion
after update of kind on public.project_items
for each row execute function public.handle_project_demotion();

create or replace function public.sync_project_action_reminder()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
declare
  reminder_row public.crm_reminders;
  reminder_status text;
  event_name text;
  reminder_found boolean := false;
begin
  if new.status = 'completed' then
    new.completed_at := coalesce(new.completed_at, now());
    reminder_status := 'completed';
  elsif new.status = 'cancelled' then
    new.completed_at := null;
    reminder_status := 'cancelled';
  else
    new.completed_at := null;
    reminder_status := 'open';
  end if;

  if new.due_at is null then
    if new.reminder_id is not null then
      update public.crm_reminders
      set status = 'cancelled', completed_at = null
      where id = new.reminder_id and owner_user_id = new.owner_user_id
      returning * into reminder_row;
      if found then
        insert into public.crm_reminder_events(reminder_id, owner_user_id, event_type, payload)
        values (new.reminder_id, new.owner_user_id, 'cancelled', jsonb_build_object('reason', 'project_action_due_date_removed'));
      end if;
    end if;
    return new;
  end if;

  if new.reminder_id is not null then
    select * into reminder_row
    from public.crm_reminders
    where id = new.reminder_id and owner_user_id = new.owner_user_id;
    reminder_found := found;
  end if;

  if not reminder_found then
    insert into public.crm_reminders (
      owner_user_id, title, details, status, due_at, next_review_at,
      completed_at, source_type, source_external_id, context
    ) values (
      new.owner_user_id,
      new.title,
      new.details,
      reminder_status,
      new.due_at,
      new.due_at,
      case when reminder_status = 'completed' then new.completed_at else null end,
      'other',
      'project_action:' || new.id::text,
      jsonb_build_object('project_action_id', new.id, 'project_id', new.project_id)
    )
    returning * into reminder_row;
    new.reminder_id := reminder_row.id;
    insert into public.crm_reminder_events(reminder_id, owner_user_id, event_type, payload)
    values (reminder_row.id, new.owner_user_id, 'created', jsonb_build_object('source', 'project_action'));
  else
    event_name := case
      when reminder_row.status in ('completed', 'cancelled') and reminder_status = 'open' then 'reopened'
      when reminder_status = 'completed' then 'completed'
      when reminder_status = 'cancelled' then 'cancelled'
      else 'updated'
    end;
    update public.crm_reminders
    set title = new.title,
        details = new.details,
        status = reminder_status,
        due_at = new.due_at,
        next_review_at = case when reminder_status = 'open' then least(new.due_at, coalesce(next_review_at, new.due_at)) else next_review_at end,
        snoozed_until = case when reminder_status = 'open' then null else snoozed_until end,
        completed_at = case when reminder_status = 'completed' then new.completed_at else null end,
        context = coalesce(context, '{}'::jsonb) || jsonb_build_object('project_action_id', new.id, 'project_id', new.project_id)
    where id = new.reminder_id and owner_user_id = new.owner_user_id;
    insert into public.crm_reminder_events(reminder_id, owner_user_id, event_type, payload)
    values (new.reminder_id, new.owner_user_id, event_name, jsonb_build_object('source', 'project_action'));
  end if;

  return new;
end;
$$;

create trigger trg_project_actions_sync_reminder
before insert or update of title, details, status, due_at, owner_user_id, project_id
on public.project_actions
for each row execute function public.sync_project_action_reminder();

