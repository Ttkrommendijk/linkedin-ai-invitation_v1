create table public.project_items (
  id uuid primary key default gen_random_uuid(),
  owner_user_id uuid not null references auth.users(id) on delete cascade,
  kind text not null check (kind in ('idea', 'project')),
  parent_project_id uuid null,
  title text not null check (btrim(title) <> ''),
  details text null,
  project_status text null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint project_items_kind_status_check check (
    (kind = 'idea' and project_status is null)
    or
    (kind = 'project' and project_status in ('active', 'paused', 'completed', 'cancelled'))
  ),
  constraint project_items_not_own_parent check (parent_project_id is null or parent_project_id <> id),
  constraint project_items_owner_identity_unique unique (id, owner_user_id),
  constraint project_items_parent_owner_fk
    foreign key (parent_project_id, owner_user_id)
    references public.project_items(id, owner_user_id)
    on delete restrict
);

create table public.project_actions (
  id uuid primary key default gen_random_uuid(),
  owner_user_id uuid not null references auth.users(id) on delete cascade,
  project_id uuid not null,
  title text not null check (btrim(title) <> ''),
  details text null,
  status text not null default 'open' check (status in ('open', 'completed', 'cancelled')),
  due_at timestamptz null,
  reminder_id uuid null references public.crm_reminders(id) on delete set null,
  completed_at timestamptz null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint project_actions_status_completed_check check (
    (status = 'completed' and completed_at is not null)
    or
    (status <> 'completed' and completed_at is null)
  ),
  constraint project_actions_owner_identity_unique unique (id, owner_user_id),
  constraint project_actions_project_owner_fk
    foreign key (project_id, owner_user_id)
    references public.project_items(id, owner_user_id)
    on delete restrict
);

create table public.project_progress_memories (
  id uuid primary key default gen_random_uuid(),
  owner_user_id uuid not null references auth.users(id) on delete cascade,
  project_id uuid not null,
  summary text not null check (btrim(summary) <> ''),
  source_type text not null default 'conversation' check (source_type in ('conversation', 'check_in', 'manual')),
  source_external_id text null,
  confidence numeric null check (confidence is null or (confidence >= 0 and confidence <= 1)),
  recorded_at timestamptz not null default now(),
  corrected_at timestamptz null,
  expires_at timestamptz null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint project_progress_memories_project_owner_fk
    foreign key (project_id, owner_user_id)
    references public.project_items(id, owner_user_id)
    on delete cascade
);

create table public.project_events (
  id bigint generated by default as identity primary key,
  owner_user_id uuid not null references auth.users(id) on delete cascade,
  project_item_id uuid not null,
  event_type text not null check (event_type in ('created', 'updated', 'promoted', 'demoted', 'status_changed')),
  payload jsonb not null default '{}'::jsonb check (jsonb_typeof(payload) = 'object'),
  created_at timestamptz not null default now(),
  constraint project_events_item_owner_fk
    foreign key (project_item_id, owner_user_id)
    references public.project_items(id, owner_user_id)
    on delete cascade
);

