create or replace function public.validate_project_item_hierarchy()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
declare
  parent_row public.project_items;
begin
  if tg_op = 'UPDATE' and old.kind = 'project' and new.kind = 'idea' and exists (
    select 1 from public.project_items child
    where child.parent_project_id = new.id
      and child.kind = 'project'
  ) then
    raise exception 'Demote child projects before demoting their parent project';
  end if;

  if new.parent_project_id is null then
    return new;
  end if;

  select * into parent_row
  from public.project_items
  where id = new.parent_project_id
    and owner_user_id = new.owner_user_id;

  if not found or parent_row.kind <> 'project' then
    raise exception 'Parent must be an owned project';
  end if;

  if new.kind = 'project' and parent_row.parent_project_id is not null then
    raise exception 'Projects support at most two hierarchy levels';
  end if;

  return new;
end;
$$;

create trigger trg_project_items_validate_hierarchy
before insert or update of kind, parent_project_id, owner_user_id
on public.project_items
for each row execute function public.validate_project_item_hierarchy();

create or replace function public.validate_project_action_parent()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  if not exists (
    select 1 from public.project_items p
    where p.id = new.project_id
      and p.owner_user_id = new.owner_user_id
      and p.kind = 'project'
  ) then
    raise exception 'Action parent must be an owned project';
  end if;
  return new;
end;
$$;

